function source(
  sourceId: string,
  originalText: string | null,
  independenceGroupId = sourceId,
  snippets: EvaluationSourceFixture["snippets"] = [],
  provenanceClass: EvaluationSourceFixture["provenanceClass"] = "community_or_user_material",
): EvaluationSourceFixture {
  const available = originalText !== null;
  return {
    sourceId,
    url: `https://example.com/source/${sourceId}`,
    independenceGroupId,
    originalStatus: available ? "available" : "unavailable",
    originalText,
    retrievedAt: available ? "2025-04-08T12:30:00.000Z" : null,
    provenanceClass,
    snippets,
  };
}

